function [R,T] = abs_pose_ini(Line,evt, Rgt)
A = zeros(10, 10);
kii = zeros(1, 9);
aii = zeros(10, 1);

for ii = 1:size(Line,2)

    dii = Line{ii}.direct;

    for jj = 1:size(evt,2)
        nii = evt{ii,jj}.eventNormal;
        kii = [dii .* nii(1), dii .* nii(2), dii .* nii(3)];
        aii(1) = sum(kii([1 5 9]));
        aii(2) = 2*(kii(8) - kii(6));
        aii(3) = 2*(kii(3) - kii(7));
        aii(4) = 2*(kii(4) - kii(2));
        aii(5) = kii(1) - kii(5) - kii(9);
        aii(6) = 2*(kii(2) + kii(4));
        aii(7) = 2*(kii(3) + kii(7));
        aii(8) = kii(5) - kii(1) - kii(9);
        aii(9) = 2*(kii(6) + kii(8));
        aii(10) = kii(9) - kii(5) - kii(1);

        A = A + aii * aii';
    end
end

A = A(:);
sols = solver_pnel_R(A);
sols = sols(:, any(not(imag(sols))));
nSol = size(sols,2);

for ii = 1:nSol
    qxyz = sols(:,ii);
    Rii = cayley2rot(qxyz);
    Rs(:,:,ii) = Rii;
    C = [];b = [];
    for jj = 1:size(Line,2)
        Ld = Line{jj}.direct;
        Lm = Line{jj}.normal;

        Rd = Rii*Ld;
        Rm = Rii*Lm;

        for kk = 1:size(evt,2)
            evtkk = evt{jj,kk}.events;
            for ll = 1:size(evtkk,2)
                ell = evtkk(:,ll);
                ckk = [Rd(2) - Rd(3)*ell(2), Rd(3)*ell(1) - Rd(1), Rd(1)*ell(2) - Rd(2)*ell(1)];
                C = [C;ckk];
                b = [b;-1*[Rm(3) + Rm(1)*ell(1) + Rm(2)*ell(2)]];
            end
        end
    end
    tii = C\b;
    ts(:,ii) = tii;
    errs(ii) = norm(C*tii-b);
    errs(ii) = norm(Rii - Rgt);
end

[minerr, idx] = min(errs);
R = Rs(:,:,idx);
T = ts(:,idx);
end


